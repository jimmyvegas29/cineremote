#!/usr/bin/env bash
# Build + install the CineRemote Camera OBS source on macOS (Apple Silicon and Intel).
# Needs: Xcode Command Line Tools (xcode-select --install). OBS.app doesn't ship headers, so this
# compiles against the libobs headers in third_party/ (fetched below).
#   - with OBS installed: matches its version and architectures and links its libobs.framework
#   - without OBS (CI, or OBS_UNIVERSAL=1): a universal arm64+x86_64 plugin against OBS_VER's headers;
#     the libobs symbols are resolved by OBS when it loads the plugin
#   ./build_macos.sh            build out/cineremote-obs.plugin
#   ./build_macos.sh --install  also copy it to ~/Library/Application Support/obs-studio/plugins
set -euo pipefail
cd "$(dirname "$0")"
if [ -z "${OBS_APP:-}" ]; then
  OBS_APP=/Applications/OBS.app
  [ -d "$OBS_APP" ] || OBS_APP="$HOME/Applications/OBS.app"     # non-admin installs
fi
FW="$OBS_APP/Contents/Frameworks"
if [ -d "$FW/libobs.framework" ] && [ -z "${OBS_UNIVERSAL:-}" ]; then
  OBS_VER=$(/usr/libexec/PlistBuddy -c "Print CFBundleShortVersionString" "$OBS_APP/Contents/Info.plist")
  # exactly the architectures the installed OBS has (the Apple Silicon OBS is arm64-only)
  ARCHS=""
  for a in $(lipo -archs "$FW/libobs.framework/libobs"); do ARCHS="$ARCHS -arch $a"; done
  LINK=(-F"$FW" -framework libobs -Wl,-rpath,@executable_path/../Frameworks)
else
  OBS_VER=${OBS_VER:-32.1.2}
  ARCHS="-arch arm64 -arch x86_64"
  LINK=(-undefined dynamic_lookup)
  echo "[build] no OBS.app: universal build against libobs $OBS_VER headers"
fi
SRC=third_party/obs-studio-$OBS_VER
if [ ! -f "$SRC/libobs/obs-module.h" ]; then
  echo "[build] fetching libobs $OBS_VER headers"
  mkdir -p third_party
  git clone -q --depth 1 --filter=blob:none --sparse --branch "$OBS_VER" https://github.com/obsproject/obs-studio.git "$SRC"
  git -C "$SRC" sparse-checkout set libobs deps/libcaption
fi
if [ ! -f third_party/simde/simde/x86/sse2.h ]; then   # header-only SIMD shim libobs includes
  echo "[build] fetching SIMDe headers"
  git clone -q --depth 1 https://github.com/simd-everywhere/simde.git third_party/simde
fi
# obsconfig.h is generated by OBS's CMake; the plugin only needs these two values.
mkdir -p out/gen
printf '#pragma once\n#define OBS_DATA_PATH "../../data"\n#define OBS_PLUGIN_PATH "../../obs-plugins"\n#define OBS_RELEASE_CANDIDATE 0\n#define OBS_BETA 0\n' > out/gen/obsconfig.h
B=out/cineremote-obs.plugin
mkdir -p "$B/Contents/MacOS" "$B/Contents/Resources/locale"
clang -O2 -fPIC -bundle -std=gnu11 -fvisibility=hidden $ARCHS -mmacosx-version-min=12.0 \
  -I"$SRC/libobs" -Ithird_party/simde -Iout/gen -Isrc src/plugin-main.c \
  "${LINK[@]}" \
  -o "$B/Contents/MacOS/cineremote-obs"
cat > "$B/Contents/Info.plist" <<'EOF'
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
  <key>CFBundleExecutable</key><string>cineremote-obs</string>
  <key>CFBundleIdentifier</key><string>com.cineremote.obs.cineremote-obs</string>
  <key>CFBundleName</key><string>cineremote-obs</string>
  <key>CFBundlePackageType</key><string>BNDL</string>
  <key>CFBundleShortVersionString</key><string>1.3.0</string>
</dict></plist>
EOF
echo 'CineRemote Camera="CineRemote Camera"' > "$B/Contents/Resources/locale/en-US.ini"
codesign --force --sign - "$B" >/dev/null 2>&1 || true    # ad-hoc signature (required on Apple Silicon)
echo "[build] OK -> $B"
if [ "${1:-}" = "--install" ]; then
  dest="$HOME/Library/Application Support/obs-studio/plugins"
  mkdir -p "$dest"
  rm -rf "$dest/cineremote-obs.plugin"
  cp -R "$B" "$dest/"
  xattr -dr com.apple.quarantine "$dest/cineremote-obs.plugin" 2>/dev/null || true
  echo "[install] $dest - restart OBS, then Add Source -> CineRemote Camera"
fi
